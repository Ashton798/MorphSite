"""StorageService：封装文件存储。

第一版使用本地 uploads/outputs 目录；以后切换对象存储（S3/OSS）时，
只需要实现同样的方法签名，业务代码不变。
"""
import re
import uuid
from pathlib import Path

from fastapi import UploadFile

from ..config import settings

ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp"}
ALLOWED_CONTENT_TYPES = {"image/jpeg", "image/png", "image/webp"}

_SAFE_NAME = re.compile(r"^[A-Za-z0-9._-]+$")


class FileValidationError(ValueError):
    """文件校验失败（类型/大小），携带中文提示。"""


class StorageService:
    def __init__(self) -> None:
        self.upload_dir = settings.upload_path
        self.output_dir = settings.output_path
        self.upload_dir.mkdir(parents=True, exist_ok=True)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    # ---------- 上传 ----------

    async def save_upload(self, file: UploadFile) -> Path:
        """校验并保存上传图片，返回保存路径。"""
        ext = Path(file.filename or "").suffix.lower()
        if ext not in ALLOWED_EXTENSIONS or (file.content_type or "") not in ALLOWED_CONTENT_TYPES:
            raise FileValidationError("文件类型不支持：仅支持 JPG、PNG、WEBP 格式的图片")

        max_bytes = settings.max_upload_mb * 1024 * 1024
        dest = self.upload_dir / f"{uuid.uuid4().hex}{ext}"
        size = 0
        try:
            with dest.open("wb") as out:
                while chunk := await file.read(1024 * 1024):
                    size += len(chunk)
                    if size > max_bytes:
                        raise FileValidationError(
                            f"文件过大：图片不能超过 {settings.max_upload_mb} MB"
                        )
                    out.write(chunk)
        except FileValidationError:
            dest.unlink(missing_ok=True)
            raise
        if size == 0:
            dest.unlink(missing_ok=True)
            raise FileValidationError("上传文件为空，请重新选择图片")
        return dest

    # ---------- 输出 ----------

    @staticmethod
    def cleanup_files(paths: list[str]) -> None:
        """删除一组已保存的文件（用于校验失败时回滚）。"""
        for p in paths:
            Path(p).unlink(missing_ok=True)

    def output_file(self, task_id: str, suffix: str) -> Path:
        """为任务生成输出文件路径，如 outputs/{task_id}_poster.png。"""
        return self.output_dir / f"{task_id}_{suffix}"

    def resolve_public_file(self, filename: str) -> Path | None:
        """根据文件名定位可公开访问的文件（仅限 outputs/uploads 目录，防止路径穿越）。"""
        if not _SAFE_NAME.match(filename):
            return None
        # Public names are generated by this service. A UUID prefix prevents
        # guessing unrelated files while preserving legacy output names.
        if not (filename.startswith("uploads-") or re.match(r"^[a-f0-9]{32}(?:_|\.)", filename)):
            return None
        for base in (self.output_dir, self.upload_dir):
            candidate = (base / filename).resolve()
            if candidate.is_file() and candidate.parent == base.resolve():
                return candidate
        return None

    @staticmethod
    def public_url(path: Path | str | None) -> str | None:
        """将本地文件路径转换为 API 访问 URL。"""
        if not path:
            return None
        return f"/api/files/{Path(path).name}"


storage_service = StorageService()
